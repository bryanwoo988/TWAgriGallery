const versioned = path => new URL(`${path}?v=${CONTENT[path]}`, self.location).href;

/* Hall text is not fetched while installing: 37 MB would hold an update back for
   minutes on a phone network, and the system may stop the worker part way. The
   app fetches each hall in the background once it runs (content.js syncHalls);
   this worker caches each response and drops that hall's older version. */
async function dropOlder(cache, key) {
  const path = new URL(key).pathname;
  for (const r of await cache.keys()) {
    if (r.url !== key && new URL(r.url).pathname === path) await cache.delete(r);
  }
}

async function pruneContent() {
  const cache = await caches.open(CONTENT_CACHE);
  const keys = await cache.keys();
  const current = new Set(Object.keys(CONTENT).map(versioned));
  const haveCurrent = new Set(keys.filter(r => current.has(r.url)).map(r => new URL(r.url).pathname));
  // Drop an old version only once the current one is in; a hall no longer listed goes too.
  await Promise.all(keys.filter(r => {
    if (current.has(r.url)) return false;
    const path = contentPath(r.url);
    return !(path in CONTENT) || haveCurrent.has(new URL(r.url).pathname);
  }).map(r => cache.delete(r)));
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const isUpdate = (await caches.keys()).some(n => n.startsWith(PREFIX) && !KEEP.has(n));
    const cache = await caches.open(CACHE);
    const results = await Promise.allSettled(SHELL_ASSETS.map(url => cache.add(new Request(url, { cache: 'reload' }))));
    const failed = results.filter(r => r.status === 'rejected').length;
    if (failed && isUpdate) {
      await caches.delete(CACHE);
      throw new Error(`precache incomplete (${failed} files)`);
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(n => n.startsWith(PREFIX) && !KEEP.has(n)).map(n => caches.delete(n)));
    await pruneContent();
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const { request } = event;
  if (request.method !== 'GET') return;
  const kind = cacheStrategy(request.url, self.location.origin);
  if (kind === 'never') return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      return (await cache.match('./')) || (await cache.match('index.html')) || fetch(request).catch(() => new Response('Offline', { status: 503 }));
    })());
    return;
  }

  if (kind === 'content') {
    event.respondWith((async () => {
      const cache = await caches.open(CONTENT_CACHE);
      const path = contentPath(request.url);
      const key = path in CONTENT ? versioned(path) : request.url;
      const hit = await cache.match(key);
      if (hit) return hit;
      try {
        const res = await fetch(key);
        if (res.ok) {
          await cache.put(key, res.clone());
          await dropOlder(cache, key);
        }
        return res;
      } catch (e) {
        // Offline with only an older version of this hall: better than nothing.
        const old = await cache.match(request.url, { ignoreSearch: true });
        return old || new Response('', { status: 504 });
      }
    })());
    return;
  }

  if (kind === 'photo') {
    event.respondWith((async () => {
      const cache = await caches.open(PHOTO_CACHE);
      const hit = await cache.match(request.url);
      if (hit) return hit;
      try {
        const res = await fetch(request);
        if (res.ok) await cache.put(request.url, res.clone());
        return res;
      } catch (e) { return new Response('', { status: 504 }); }
    })());
    return;
  }

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(request, { ignoreSearch: true });
    if (hit) return hit;
    try { return await fetch(request); } catch (e) { return new Response('', { status: 504 }); }
  })());
});
