// Other apps live on the same github.io origin; only caches with this prefix are ours.
const PREFIX = 'twagri-';

function cacheStrategy(urlString, selfOrigin) {
  let u;
  try { u = new URL(urlString); } catch (e) { return 'never'; }
  return u.origin === selfOrigin ? 'precache' : 'never';
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const isUpdate = (await caches.keys()).some(n => n.startsWith(PREFIX) && n !== CACHE);
    const cache = await caches.open(CACHE);
    // One by one: on a first install a single failure must not leave the app uninstalled.
    const results = await Promise.allSettled(ASSETS.map(url => cache.add(new Request(url, { cache: 'reload' }))));
    const failed = results.map((r, i) => (r.status === 'rejected' ? ASSETS[i] : null)).filter(Boolean);
    if (failed.length) {
      console.warn('[sw] could not precache:', failed);
      if (isUpdate) {
        // Keep the old complete copy; the browser retries the update later.
        await caches.delete(CACHE);
        throw new Error(`precache incomplete (${failed.length} files)`);
      }
    }
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(n => n.startsWith(PREFIX) && n !== CACHE).map(n => caches.delete(n)));
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const { request } = event;
  if (request.method !== 'GET') return;
  if (cacheStrategy(request.url, self.location.origin) !== 'precache') return;

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(CACHE);
      return (await cache.match('./')) || (await cache.match('index.html')) || fetch(request).catch(() => new Response('Offline', { status: 503 }));
    })());
    return;
  }

  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const hit = await cache.match(request, { ignoreSearch: true });
    if (hit) return hit;
    try { return await fetch(request); } catch (e) { return new Response('', { status: 504 }); }
  })());
});
