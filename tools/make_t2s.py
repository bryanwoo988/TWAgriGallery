#!/usr/bin/env python3
"""Write js/t2s-data.js from OpenCC's t2s dictionaries (TSPhrases + TSCharacters),
so the app converts 繁體 article text to 简体 on the phone instead of shipping both.
    python3 tools/make_t2s.py"""
import json, os
import opencc
D = os.path.join(os.path.dirname(opencc.__file__), "dictionary")
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

def load(name):
    out = {}
    for line in open(os.path.join(D, name), encoding="utf-8"):
        if "\t" in line:
            k, v = line.rstrip("\n").split("\t")
            out[k] = v.split(" ")[0]
    return out

chars, phrases = load("TSCharacters.txt"), load("TSPhrases.txt")
with open(os.path.join(ROOT, "js", "t2s-data.js"), "w", encoding="utf-8") as f:
    f.write("/* Generated by tools/make_t2s.py from OpenCC (Apache-2.0): TSCharacters + TSPhrases. */\n")
    f.write("export const CHARS = " + json.dumps(chars, ensure_ascii=False, separators=(",", ":")) + ";\n")
    f.write("export const PHRASES = " + json.dumps(phrases, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(len(chars), "chars,", len(phrases), "phrases")
